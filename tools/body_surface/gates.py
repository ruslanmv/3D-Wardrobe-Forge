#!/usr/bin/env python3
"""CG1. Character gates for the bare body state: audit, check a candidate, record a review.

    python tools/body_surface/gates.py audit [--md docs/qa/CHARACTER_GATE_AUDIT.md]
    python tools/body_surface/gates.py check --file candidate.vrm [--declared-adult]
    python tools/body_surface/gates.py record --file x.vrm --sha256 <hex> --outcome clearly-adult \\
        --reviewer "Name" --evidence "what was looked at" [--packet packet.json] [--date YYYY-MM-DD]

``audit`` and ``check`` read only. ``record`` is for the person who reviewed the file, run under
their own name, and writes one entry to ``adult-design-reviews.json`` keyed by the file's SHA-256 —
the approval that then holds for those bytes without being asked again. See
``wardrobe.body_surface.character_gates`` for what each status means and what is never inferred.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from wardrobe.body_surface.character_gates import (  # noqa: E402
    REVIEW_OUTCOMES,
    measure_body_state,
    record_review,
    status,
)
from wardrobe.config import Settings  # noqa: E402
from wardrobe.library import AvatarLibrary  # noqa: E402


def body_of(path: Path) -> dict:
    """Is the authored body closed with every detected garment counted out, and is her clothing a
    garment or paint? (CG4: ``character_gates.measure_body_state``, CV1's analysis.) Nothing is changed."""
    return measure_body_state(path)


REVIEW_LABEL = {"pending": "pending (not reviewed yet)"}
BODY_LABEL = {
    "complete": "complete",
    "painted-on": "clothing painted on: needs a body-state file",
    "body-missing": "body missing ({bands})",
    "not-measured": "not measured",
}


def _body_label(answer: dict) -> str:
    label = BODY_LABEL.get(answer["state"], answer["state"]).format(bands=", ".join(answer["missingBands"]))
    if answer["state"] == "complete" and (answer.get("paintedShare") or 0) > 0.02:
        share = f"{answer['paintedShare']:.0%}"
        label += f" (a painted layer under the garments, {share}: bare restores the skin)"
    if answer.get("bodyStateFiles"):
        label += f"; {answer['bodyStateFiles']} body-state file(s) imported"
    return label


def markdown(rows: list[dict], missing: list[str] | None = None) -> str:
    out = ["# Character gate audit (generated by `tools/body_surface/gates.py audit`)", "",
           "One row per library character, for the exact file on disk. `eligible` opens the bare body "
           "state (with the operator's switch on, for a viewer who has confirmed they are an adult in "
           "Private Mode); every other status lists what is missing and who acts. Nothing here is a "
           "review, and a user's own adult confirmation never stands in for one.", "",
           "A review that is `pending` is work not yet done, not a rejection: only a finding a person "
           "recorded (`age-ambiguous`, `appears-minor`, `not-assessable`) blocks a file. Body is "
           "tracked on its own (CV1's clothing structure for the exact file).", "",
           "| Character | SHA-256 | Sexual use | Modification | Declared adult | Review | Body | Status |",
           "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        licence = r["licence"]
        review = r["review"]
        review_cell = (f"{review['outcome']} ({review['reviewer']}, {review['date']})" if review
                       else f"**{REVIEW_LABEL['pending']}**")
        out.append(" | ".join([
            f"| {r['title'] or r['slug']}", f"`{r['sha256']}`",
            "allowed (file)" if licence["sexualUse"] else "**refused by the file**",
            f"allowed ({licence['modificationSource']})" if licence["modification"] else "**not stated**",
            "yes" if r["operatorDeclaration"] else "no",
            review_cell, _body_label(r["bodyState"]), f"**{r['status']}** |"]))
    out += ["", "## What each needs", ""]
    for r in rows:
        out.append(f"**{r['title'] or r['slug']}** (`{r['sha256'][:12]}`): {r['status']}"
                   + (f" — {'; '.join(r['blockedBecause'])}" if r["blockedBecause"] else ""))
        out += [f"- {q['owner']}: {q['what']}" for q in r["requirements"]] or ["- nothing"]
        out.append("")
    if missing:
        out += ["## Not on this disk", "",
                "Listed in the library but not fetched (`tools/fetch_library.py`); not evaluated:", ""]
        out += [f"- {slug}" for slug in missing]
        out.append("")
    return "\n".join(out)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = parser.add_subparsers(dest="command", required=True)
    a = sub.add_parser("audit")
    a.add_argument("--md", type=Path)
    a.add_argument("--json", type=Path)
    c = sub.add_parser("check")
    c.add_argument("--file", type=Path, required=True)
    c.add_argument("--declared-adult", action="store_true",
                   help="the operator intends to declare it adult (a declaration, never a review)")
    r = sub.add_parser("record")
    r.add_argument("--file", type=Path, required=True)
    r.add_argument("--sha256", required=True)
    r.add_argument("--outcome", required=True, choices=REVIEW_OUTCOMES)
    r.add_argument("--reviewer", required=True)
    r.add_argument("--evidence", required=True)
    r.add_argument("--packet", type=Path)
    r.add_argument("--date", default=date.today().isoformat())
    args = parser.parse_args(argv)
    settings = Settings(_env_file=None)

    if args.command == "record":
        registry = Path(settings.body_surface_root_path) / "adult-design-reviews.json"
        entry = record_review(registry, file=args.file, sha256=args.sha256, outcome=args.outcome,
                              reviewer=args.reviewer, evidence=args.evidence, date=args.date,
                              packet=args.packet)
        print(f"recorded for {args.sha256}: {json.dumps(entry, ensure_ascii=False)}\n"
              f"commit {registry.relative_to(ROOT) if registry.is_relative_to(ROOT) else registry} "
              "under your own name")
        return 0

    library = AvatarLibrary.from_directory(ROOT / "assets" / "library")
    if args.command == "check":
        row = status(args.file, slug=None, depicts_adult=args.declared_adult, pinned_sha256=None,
                     settings=settings, body=body_of(args.file))
        print(json.dumps(row, indent=1, ensure_ascii=False, default=str))
        return 0 if row["status"] == "eligible" else 1

    rows = []
    for avatar in library.available():
        rows.append(status(avatar.path, slug=avatar.slug, depicts_adult=avatar.depicts_adult,
                           pinned_sha256=avatar.sha256, settings=settings, body=body_of(avatar.path),
                           library_conditions=avatar.granted_conditions))
        print(f"{avatar.slug:24} {rows[-1]['sha256'][:12]} {rows[-1]['status']}")
    missing = [avatar.slug for avatar in library.avatars if not avatar.available]
    for slug in missing:
        print(f"{slug:24} not on this disk (tools/fetch_library.py)")
    if args.json:
        args.json.write_text(json.dumps(rows, indent=1, ensure_ascii=False, default=str))
    if args.md:
        args.md.write_text(markdown(rows, missing), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
