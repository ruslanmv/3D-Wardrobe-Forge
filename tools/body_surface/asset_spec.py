#!/usr/bin/env python3
"""AS1. One specification per library character, and a pre-flight for the file that comes back.

    python tools/body_surface/asset_spec.py --all --out docs/qa/body-state-specs
    python tools/body_surface/asset_spec.py --slug avatar-sample-a --out /tmp/spec
    python tools/body_surface/asset_spec.py --preflight --slug avatar-sample-a \\
        --candidate delivered.vrm --state bare [--sha256 <hex>] [--json verdict.json]

``docs/qa/BODY_STATE_CHARACTERS.md`` says where the eight characters stand, in one table. A
person commissioning, making or checking a body-state file for *one* of them needs that
character's own sheet: the exact source file, what its terms say, which of its nodes the import
will hold a delivered file to, bone by bone and mesh by mesh, and the commands with her slug and
hash already in them. Written by hand, eight such sheets would be eight chances to mistype a
hash or a bone's node name; these are read from the files.

**The specification** (``--slug`` / ``--all``) reads the clothed source file only and decides
nothing. Per character it writes ``<slug>.md``:

* the exact file (path, bytes, SHA-256, the library pin), VRM version, title, authors;
* the creator's terms as the file states them and as the library records them, and what that
  leaves undocumented;
* whether a review of this exact file is recorded (it reports the registry; it is not a review);
* the body as authored: the repository's own readiness record for this hash
  (``docs/qa/BARE_READINESS.md``), her skin surface's size, and the clothing meshes she wears;
* the identity an imported file must keep: every humanoid bone with its node name and rest
  position, every expression, every face and hair primitive with its vertex and morph counts;
* the two routes for this slot and which is open, and the commands for each step.

``--all`` also writes ``README.md``: the shared rules, and the completion matrix.

**The pre-flight** (``--preflight``) runs the import's own verdict
(``wardrobe.body_surface.body_state_import.check``) on a delivered file, on a workstation, with
no server: the same checks, in the same order, with every answer printed. It separates what the
file is (structure: hash, binding, rig, expressions, face and hair, clothing, body closure) from
who may have it (eligibility: the five answers for the source file and for this file), so an
artist can see that a file is structurally accepted while the reviews are still outstanding.
It registers nothing, writes no registry, and exits 0 only when the import would accept.
"""

