def readiness_record(sha256: str) -> dict | None:
    """This hash's row of the committed readiness report (generated by tools/audit/bare_readiness.py)."""
    if not READINESS.is_file():
        return None
    for line in READINESS.read_text().splitlines():
        cells = [cell.strip() for cell in line.strip().strip("|").split("|")]
        if len(cells) >= 8 and cells[1].strip("`") == sha256[:12]:
            return {"body": cells[5].strip("*"), "skin": cells[6].strip("*"), "status": cells[7].strip("*")}
    return None


def _count(document: GltfDocument, primitive: dict) -> tuple[int, int]:
    accessors = document.gltf["accessors"]
    vertices = int(accessors[primitive["attributes"]["POSITION"]]["count"])
    indices = primitive.get("indices")
    triangles = int(accessors[indices]["count"]) // 3 if indices is not None else 0
    return vertices, triangles


def specification(path: Path, slug: str, library: AvatarLibrary, settings: Settings) -> dict:
    """Everything a sheet says, as data. Reads ``path`` and the registries; writes nothing."""
    packet = review_packet.packet(path, slug=slug, library=library, settings=settings)
    document = GltfDocument.from_bytes(path.read_bytes())
    info = inspect_document(document)
    entry = library.get(slug)
    bones = []
    for bone, node in sorted(info.humanoid_bones.items()):
        at = document.node_world_position(node)
        bones.append({"bone": bone, "node": document.nodes[node].get("name"),
                      "restMm": [round(float(v) * 1000, 1) for v in at]})
    identity = []
    names = [mesh.get("name", "") for mesh in document.meshes]
    materials = document.materials
    for mesh_name, index, node_name, _accessor in body_state_import.identity_primitives(
            document, info.humanoid_bones.get("head")):
        primitive = document.meshes[names.index(mesh_name)]["primitives"][index]
        vertices, triangles = _count(document, primitive)
        material = primitive.get("material")
        identity.append({"mesh": mesh_name, "primitive": index, "node": node_name,
                         "material": materials[material].get("name") if material is not None else None,
                         "vertices": vertices, "triangles": triangles,
                         "morphTargets": len(primitive.get("targets", []))})
    garments = []
    for garment in garment_inventory(document):
        vertices, triangles = _count(document, document.meshes[garment.mesh]["primitives"][garment.primitive])
        garments.append({"slot": garment.slot, "material": garment.material,
                         "mesh": names[garment.mesh], "primitive": garment.primitive,
                         "dressLength": garment.dress_length, "vertices": vertices, "triangles": triangles})
    from wardrobe.body_art.surfaces import read_surfaces  # it reads the whole document

    skin = read_surfaces(document).skin
    checks = packet["eligibilityNow"]["checks"]
    return {
        "schema": "wardrobe.bodySurface.assetSpec.v1",
        "slug": slug,
        "name": entry.name if entry is not None else slug,
        "file": {**packet["file"],
                 "path": str(path.relative_to(ROOT)) if path.is_relative_to(ROOT) else str(path)},
        "spec": packet["whatTheFileSays"]["spec"],
        "title": packet["whatTheFileSays"]["title"],
        "licenceInFile": packet["whatTheFileSays"]["licence"],
        "libraryRecord": {
            "licence": entry.license if entry is not None else None,
            "creator": entry.creator if entry is not None else None,
            "source": entry.source if entry is not None else None,
            "conditions": entry.license_conditions if entry is not None else None,
        },
        "filePermitsSexualExpression": checks["author-permission"]["passed"],
        "declaredAdultByOperator": packet["operatorDeclaration"]["depictsAdult"],
        "reviewRecorded": checks["design-clearance"]["passed"],
        "readiness": readiness_record(packet["file"]["sha256"]),
        "skin": {"vertices": int(skin.positions.shape[0]), "triangles": int(skin.triangles.shape[0])},
        "garments": garments,
        "bones": bones,
        "expressions": sorted(info.expressions),
        "identity": identity,
        "inTheApp": slug in IN_THE_APP,
    }


def _table(head: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(str(cell) for cell in row) + " |" for row in rows]
    return "\n".join(out) + "\n"


def _modification(spec: dict) -> tuple[str, bool]:
    """What documents the right to modify, and whether the file itself states it."""
    in_file = spec["licenceInFile"].get("modification")
    url = spec["licenceInFile"].get("licenseUrl") or ""
    conditions = spec["libraryRecord"]["conditions"] or {}
    if in_file and in_file != "unknown":
        return f"the file states it: `{in_file}`", True
    if "modification=allow" in url:
        return "the file states it through its licence URL (`modification=allow`)", True
    recorded = f"the library records `{conditions.get('modification')}`" if conditions.get("modification") \
        else f"the library records the licence as `{spec['libraryRecord']['licence']}`"
    return (f"**the file does not state it** (`{in_file}`); {recorded}. The operator must hold the "
            "creator's terms in writing before commissioning a modified file"), False


def blockers(spec: dict) -> list[tuple[str, str]]:
    """What stands between this slot and an accepted body state: (what, who), in order."""
    out = []
    if not _modification(spec)[1]:
        out.append(("Document the right to modify this file (creator's terms in writing)", "operator"))
    if not spec["reviewRecorded"]:
        out.append((f"Review the exact source file `{spec['file']['sha256'][:12]}…` and record the "
                    "finding; only `clearly-adult` opens route 1, any other finding means route 2",
                    "independent reviewer"))
    readiness = spec["readiness"] or {}
    if readiness.get("body") != "complete":
        out.append(("Supply the missing body geometry as a new source file (its own hash, its own review)",
                    "licensed 3D artist"))
    out.append(("Build (`body-bare-v1`) or deliver the completed body-state VRM; pass the pre-flight",
                "operator / licensed 3D artist"))
    out.append(("Review the exact output file and record the finding", "independent reviewer"))
    if not spec["inTheApp"]:
        out.append(("Ship this character in the companion app and pin her to this slug "
                    "(`vendor/avatars/`, `src/wardrobe/AvatarIdentity.js`): the app's driver cannot "
                    "open a character the app does not ship", "operator"))
    out.append(("Import, issue a read grant, run the acceptance driver (desktop EN, phone IT)", "operator"))
    return out


