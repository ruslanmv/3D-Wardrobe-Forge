def preflight(candidate: Path, original: Path, slug: str, library: AvatarLibrary, settings: Settings, *,
              state: str, declared_sha256: str | None) -> dict:
    """The import's verdict for ``candidate`` as ``state`` of ``slug``, with the two halves told apart."""
    entry = library.get(slug)
    data, source = candidate.read_bytes(), original.read_bytes()
    verdict = body_state_import.check(
        data, source, state=state, source_sha256=hashlib.sha256(source).hexdigest(),
        declared_sha256=declared_sha256, operator_enabled=settings.wardrobe_adult_body_surface,
        depicts_adult=bool(entry is not None and entry.depicts_adult),
        review_root=settings.body_surface_root_path, reference_root=settings.wardrobe_calibration_root)
    checks = verdict.checks
    made = [name for name in STRUCTURE if name in checks]
    structural = len(made) == len(STRUCTURE) and all(checks[name]["passed"] for name in made)
    return {
        "slug": slug, "state": state, "candidate": str(candidate), "sha256": verdict.sha256,
        "sourceSha256": hashlib.sha256(source).hexdigest(),
        "accepted": verdict.accepted, "reason": verdict.reason, "message": verdict.message,
        "structurallyAccepted": structural,
        "eligible": all(checks.get(name, {}).get("passed") for name in ELIGIBILITY),
        "checks": checks,
    }


def preflight_text(result: dict) -> str:
    checks = result["checks"]
    lines = [f"{result['candidate']}", f"  sha256 {result['sha256']}",
             f"  as the {result['state']} state of {result['slug']} (source {result['sourceSha256']})", "",
             "The file:"]
    for name in STRUCTURE:
        if name not in checks:
            lines.append(f"  not reached  {name}")
            continue
        detail = {k: v for k, v in checks[name].items() if k != "passed" and v not in (None, [], "", {})}
        lines.append(f"  {'pass' if checks[name]['passed'] else 'FAIL'}         {name}  "
                     f"{json.dumps(detail)[:200] if not checks[name]['passed'] else ''}".rstrip())
    lines += ["", "Who may have it:"]
    for name in ELIGIBILITY:
        if name not in checks:
            lines.append(f"  not reached  {name}")
            continue
        refused = checks[name].get("refusedBy")
        lines.append(f"  {'pass' if checks[name]['passed'] else 'FAIL'}         {name}"
                     + (f"  refused by {refused}" if refused else ""))
    lines += ["", f"Structure: {'accepted' if result['structurallyAccepted'] else 'not accepted'}.",
              f"Import as things stand: {'ACCEPTED' if result['accepted'] else 'REFUSED'}"
              + (f" ({result['reason']}: {result['message']})" if not result["accepted"] else "") + "."]
    return "\n".join(lines) + "\n"


def _source(library: AvatarLibrary, slug: str) -> Path:
    entry = library.get(slug)
    if entry is None or entry.path is None or not Path(entry.path).is_file():
        raise SystemExit(f"{slug} is not in the library here (tools/fetch_library.py)")
    return Path(entry.path)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--slug")
    parser.add_argument("--all", action="store_true", help="every library character, and README.md")
    parser.add_argument("--out", type=Path)
    parser.add_argument("--preflight", action="store_true")
    parser.add_argument("--candidate", type=Path)
    parser.add_argument("--state", default="bare", choices=body_state_import.STATES)
    parser.add_argument("--sha256", default=None, help="the SHA-256 the delivered file is stated to have")
    parser.add_argument("--json", type=Path, default=None)
    args = parser.parse_args(argv)
    settings = Settings(_env_file=None) if not args.preflight else Settings()
    library = AvatarLibrary.from_directory(ROOT / "assets" / "library")
    if args.preflight:
        if not args.slug or args.candidate is None or not args.candidate.is_file():
            raise SystemExit("--preflight needs --slug and --candidate <file.vrm>")
        result = preflight(args.candidate, _source(library, args.slug), args.slug, library, settings,
                           state=args.state, declared_sha256=args.sha256)
        print(preflight_text(result), end="")
        if args.json:
            args.json.write_text(json.dumps(result, indent=1) + "\n")
        return 0 if result["accepted"] else 1
    if args.out is None or bool(args.slug) == bool(args.all):
        raise SystemExit("name --slug or --all, and --out")
    args.out.mkdir(parents=True, exist_ok=True)
    slugs = [avatar.slug for avatar in library.avatars] if args.all else [args.slug]
    specs = []
    for slug in slugs:
        entry = library.get(slug)
        if entry is None or entry.path is None or not Path(entry.path).is_file():
            if args.all:
                print(f"{slug}: not on this disk, no sheet written (tools/fetch_library.py)")
                continue
            raise SystemExit(f"{slug} is not in the library here (tools/fetch_library.py)")
        spec = specification(Path(entry.path), slug, library, settings)
        (args.out / f"{slug}.md").write_text(markdown(spec))
        specs.append(spec)
        print(f"{spec['file']['sha256']}  {slug}.md")
    if args.all:
        (args.out / "README.md").write_text(readme(specs))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
