"""BE2. Bare build readiness per library character: what is done, what is missing, who decides.

    python tools/audit/bare_readiness.py [--json work/bare-readiness.json] [--md docs/qa/BARE_READINESS.md]

For every available library avatar this reads, and writes nothing to any registry:

* the file's SHA-256, checked against the manifest's pinned hash (a mismatch is a blocker);
* the four concerns, each from its own owner: operator declaration (``policy.json``), author
  licence (the VRM's terms, via the gate), design clearance (``adult-design-reviews.json`` /
  ``synthetic-references.json`` for these exact bytes), body completeness and skin restoration
  (``tools/audit/bare_visibility.py``: geometry and texture only, nothing stored or rendered);
* the plan-only prebuild: the exact request ``tools/prebuild.py --only body-bare-v1`` would send
  for this slug, and the command to run once the character is cleared.

Status per character:

* ``ready-to-prebuild`` — every concern passes; the prebuild can run (with the switch on).
* ``awaiting-design-review`` — technically ready; the only missing piece is a person's review
  of this exact file. The report lists the file and hash to review. Nothing here fills it in.
* ``blocked-geometry`` — the authored body is incomplete; removal cannot fix it (M6 scope).
* ``blocked-<concern>`` — anything else that fails, named.
"""

from __future__ import annotations

import argparse
import asyncio
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))

import prebuild  # noqa: E402

from wardrobe.body_surface.eligibility import assess  # noqa: E402
from wardrobe.config import Settings  # noqa: E402
from wardrobe.library import AvatarLibrary  # noqa: E402
from wardrobe.vrm.document import GltfDocument  # noqa: E402
from wardrobe.vrm.inspect import inspect_document  # noqa: E402

sys.path.insert(0, str(ROOT / "tools" / "audit"))
from bare_visibility import audit as technical_audit  # noqa: E402


def status_of(eligibility: dict, technical: dict, hash_ok: bool) -> str:
    if not hash_ok:
        return "blocked-file-hash"
    failed = [k for k, c in eligibility["checks"].items()
              if not c["passed"] and k not in ("operator-switch", "design-clearance")]
    if failed:
        return f"blocked-{failed[0]}"
    if not technical["result"].startswith("built"):
        return "blocked-geometry"
    if technical.get("skinRestoration") == "unverified":
        return "blocked-skin-unverified"
    if not eligibility["checks"]["design-clearance"]["passed"]:
        return "awaiting-design-review"
    return "ready-to-prebuild"


def assess_avatar(avatar, settings: Settings) -> dict:
    data = avatar.path.read_bytes()
    sha = hashlib.sha256(data).hexdigest()
    terms = inspect_document(GltfDocument.from_bytes(data)).license
    # The operator switch is a deployment setting, not a property of the character: it is asked
    # as "would pass with the switch on", and the report says it must be on to prebuild.
    eligibility = assess(terms=terms, operator_enabled=True, depicts_adult=avatar.depicts_adult,
                         private=True, source_sha256=sha, review_root=settings.body_surface_root_path,
                         reference_root=settings.wardrobe_calibration_root).to_dict()
    technical = asyncio.run(technical_audit(avatar.path))
    pair = {"slug": avatar.slug, "templateId": "body-bare-v1", "name": "Bare authored body", "color": None}
    return {
        "slug": avatar.slug, "name": avatar.name, "file": avatar.file,
        "sha256": sha, "manifestSha256": avatar.sha256, "hashMatchesManifest": sha == avatar.sha256,
        "concerns": {
            "operatorDeclaration": avatar.depicts_adult,
            "authorLicence": eligibility["checks"]["author-permission"],
            "designClearance": eligibility["checks"]["design-clearance"],
            "bodyCompleteness": technical["result"],
            "skinRestoration": technical.get("skinRestoration"),
        },
        "technical": technical,
        "status": status_of(eligibility, technical, sha == avatar.sha256),
        "planOnlyPrebuild": {
            "request": prebuild.job_body(pair),
            "route": f"POST /v1/library/{avatar.slug}/jobs (bare is forced private by the route)",
            "command": ("WARDROBE_ADULT_BODY_SURFACE=true  # on the Forge that builds\n"
                        f"python tools/prebuild.py --forge <url> --admin-token-file <file> "
                        f"--only body-bare-v1 --slugs {avatar.slug}"),
        },
    }


def markdown(rows: list[dict]) -> str:
    lines = ["# Bare build readiness (generated by `tools/audit/bare_readiness.py`)", "",
             "| Character | SHA-256 (first 12) | Declared adult | Author licence | Design clearance "
             "| Body | Skin | Status |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        c = r["concerns"]
        clearance = c["designClearance"]["clearance"]
        lines.append(" | ".join([
            f"| {r['name']}", f"`{r['sha256'][:12]}`", "yes" if c["operatorDeclaration"] else "**no**",
            "allows" if c["authorLicence"]["passed"] else "**refuses**",
            clearance["kind"] if clearance else "**none recorded**",
            "complete" if c["bodyCompleteness"] == "built" else "**incomplete**",
            c["skinRestoration"] or "n/a", f"**{r['status']}** |"]))
    lines += ["", "Nothing in this report is a review. A clearance comes only from a person's entry in "
              "`assets/body_surface/adult-design-reviews.json` for the exact SHA-256 above, or, for "
              "Forge's own generated bodies, `assets/calibration/synthetic-references.json`.", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--json", type=Path, default=ROOT / "work" / "bare-readiness.json")
    parser.add_argument("--md", type=Path)
    args = parser.parse_args(argv)
    settings = Settings()
    library = AvatarLibrary.from_directory(settings.wardrobe_library_root)
    rows = [assess_avatar(a, settings) for a in library.available()]
    for r in rows:
        print(f"{r['slug']:24} {r['sha256'][:12]} {r['status']}")
    args.json.parent.mkdir(parents=True, exist_ok=True)
    args.json.write_text(json.dumps(rows, indent=1, default=str))
    if args.md:
        args.md.write_text(markdown(rows), encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
